export const ui: Record<Lang, Dict> = { en, pt, es };
export type UIKey = keyof Dict;

export function useT(lang: Lang) {
  return (key: UIKey) => ui[lang][key] ?? ui.en[key];
}

/** Monta um caminho interno com o prefixo do idioma. */
export function path(lang: Lang, p = "") {
  const clean = p.replace(/^\/+|\/+$/g, "");
  return `/${lang}/${clean ? clean + "/" : ""}`;
}

export function formatDate(lang: Lang, d: Date) {
  return new Intl.DateTimeFormat(htmlLang[lang], { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" }).format(d);
}
